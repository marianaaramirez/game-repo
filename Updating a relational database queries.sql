UPDATE PlayerStats ps
  LEFT JOIN (
SELECT
r.playerID,
r.world_level,
SUM(r.enemies_defeated) AS enemies_defeated,
SUM(r.duration) AS time_played
FROM Run r
GROUP BY r.playerID, r.world_level
) rs ON ps.playerID = rs.playerID AND ps.world_number = rs.world_level
  LEFT JOIN (
SELECT
r.playerID,
p.world_level,
SUM(p.is_correct) AS problems_solved,
AVG(CASE WHEN p.is_correct THEN p.response_time END) AS average_speed
FROM ProblemStats p
  JOIN Run r ON p.runID = r.runID
GROUP BY r.playerID, p.world_level
) pr ON ps.playerID = pr.playerID AND ps.world_number = pr.world_level
SET
ps.enemies_defeated = COALESCE(rs.enemies_defeated, 0),
ps.time_played = COALESCE(rs.time_played, 0),
ps.problems_solved = COALESCE(pr.problems_solved, 0),
ps.average_speed = COALESCE(pr.average_speed, 0),
ps.difficulty_progress = CASE
  WHEN ps.world_number = 1 THEN 'tier_1'
  WHEN ps.world_number = 2 THEN 'tier_2'
ELSE 'tier_3'
END;

